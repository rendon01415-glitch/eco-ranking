-- ============================================================================
-- EcoRanking · Esquema de base de datos (PostgreSQL 14+)
-- ----------------------------------------------------------------------------
-- Modelo: monolito relacional. Los puntos NO se guardan como un contador
-- editable: se derivan de dos libros de movimientos inmutables
--   * eventos_reciclaje  (lo que reporta el contenedor: cámara + sensor)
--   * ajustes_puntos     (penalizaciones / bonificaciones del administrador)
-- y las vistas v_* calculan totales y rankings. Así cada punto es trazable.
-- ============================================================================

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;   -- crypt(), gen_salt(), digest(), gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS citext;     -- emails sin distinción de mayúsculas

-- ----------------------------------------------------------------------------
-- Utilidad: updated_at automático
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ----------------------------------------------------------------------------
-- 1. instituciones  (preparado para multi-colegio a futuro)
-- ----------------------------------------------------------------------------
CREATE TABLE instituciones (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       VARCHAR(200) NOT NULL,
  codigo_dane  VARCHAR(20)  UNIQUE,
  municipio    VARCHAR(100),
  activo       BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- 2. periodos_competencia
-- ----------------------------------------------------------------------------
CREATE TABLE periodos_competencia (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institucion_id        BIGINT       NOT NULL REFERENCES instituciones(id),
  nombre                VARCHAR(150) NOT NULL,
  fecha_inicio          DATE         NOT NULL,
  fecha_fin             DATE         NOT NULL,
  estado                VARCHAR(12)  NOT NULL DEFAULT 'planificado'
                        CHECK (estado IN ('planificado','activo','cerrado','archivado')),
  ganadores_publicados  BOOLEAN      NOT NULL DEFAULT FALSE,
  created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CHECK (fecha_fin > fecha_inicio)
);
-- Regla de negocio: un solo periodo activo por institución
CREATE UNIQUE INDEX uq_periodo_activo ON periodos_competencia (institucion_id)
  WHERE estado = 'activo';

-- ----------------------------------------------------------------------------
-- 3. materiales_reciclables  (configurables por el administrador)
-- ----------------------------------------------------------------------------
CREATE TABLE materiales_reciclables (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR(100) NOT NULL UNIQUE,
  codigo_modelo VARCHAR(50)  NOT NULL UNIQUE,   -- clase que devuelve el modelo de visión
  puntos_base   INTEGER      NOT NULL CHECK (puntos_base > 0),
  activo        BOOLEAN      NOT NULL DEFAULT TRUE,
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- 4. salones
--    categoria se DERIVA del grado: A = 1..5, B = 6..11 (no puede quedar inconsistente)
-- ----------------------------------------------------------------------------
CREATE TABLE salones (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institucion_id  BIGINT      NOT NULL REFERENCES instituciones(id),
  grado           SMALLINT    NOT NULL CHECK (grado BETWEEN 1 AND 11),
  nombre          VARCHAR(20) NOT NULL,                 -- '4A', '7B', '11A'
  categoria       CHAR(1)     GENERATED ALWAYS AS
                    (CASE WHEN grado <= 5 THEN 'A' ELSE 'B' END) STORED,
  director_id     BIGINT,                               -- FK a usuarios (se añade abajo)
  activo          BOOLEAN     NOT NULL DEFAULT TRUE,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (institucion_id, nombre)
);

-- ----------------------------------------------------------------------------
-- 5. usuarios  (administrador | director | estudiante)
-- ----------------------------------------------------------------------------
CREATE TABLE usuarios (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institucion_id  BIGINT       NOT NULL REFERENCES instituciones(id),
  nombre          VARCHAR(150) NOT NULL,
  email           CITEXT       NOT NULL UNIQUE,
  password_hash   TEXT         NOT NULL,                -- bcrypt, NUNCA texto plano
  rol             VARCHAR(13)  NOT NULL
                  CHECK (rol IN ('administrador','director','estudiante')),
  salon_id        BIGINT       REFERENCES salones(id),  -- solo estudiantes
  activo          BOOLEAN      NOT NULL DEFAULT TRUE,
  ultimo_login    TIMESTAMPTZ,
  created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CHECK (rol <> 'estudiante' OR salon_id IS NOT NULL),
  CHECK (rol =  'estudiante' OR salon_id IS NULL)
);

-- Un docente dirige un solo salón (varios NULL permitidos)
ALTER TABLE salones
  ADD CONSTRAINT fk_salones_director
  FOREIGN KEY (director_id) REFERENCES usuarios(id) ON DELETE SET NULL;
CREATE UNIQUE INDEX uq_salon_director ON salones (director_id) WHERE director_id IS NOT NULL;

-- ----------------------------------------------------------------------------
-- 6. contenedores  (contenedor inteligente = cámara + sensor)
--    Supuesto: cada contenedor acredita sus puntos al salón vinculado.
-- ----------------------------------------------------------------------------
CREATE TABLE contenedores (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  institucion_id   BIGINT       NOT NULL REFERENCES instituciones(id),
  codigo           VARCHAR(50)  NOT NULL UNIQUE,        -- 'ECO-001'
  ubicacion        TEXT,
  salon_id         BIGINT       NOT NULL REFERENCES salones(id),
  modelo_hardware  VARCHAR(100),
  firmware_version VARCHAR(20),
  estado           VARCHAR(13)  NOT NULL DEFAULT 'activo'
                   CHECK (estado IN ('activo','inactivo','mantenimiento','offline')),
  ultima_conexion  TIMESTAMPTZ,
  api_key_hash     TEXT         NOT NULL,               -- sha256(hex) de la clave del dispositivo
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- 7. eventos_reciclaje  (libro de eventos del hardware, inmutable salvo revisión)
-- ----------------------------------------------------------------------------
CREATE TABLE eventos_reciclaje (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uid_evento         UUID         NOT NULL DEFAULT gen_random_uuid(), -- idempotencia (lo genera el dispositivo)
  contenedor_id      BIGINT       NOT NULL REFERENCES contenedores(id),
  salon_id           BIGINT       NOT NULL REFERENCES salones(id),     -- snapshot del salón acreditado
  periodo_id         BIGINT       NOT NULL REFERENCES periodos_competencia(id),
  estudiante_id      BIGINT       REFERENCES usuarios(id),             -- NULL si no hay identificación
  material_id        BIGINT       REFERENCES materiales_reciclables(id),
  ocurrido_en        TIMESTAMPTZ  NOT NULL,
  confianza_camara   NUMERIC(5,2) CHECK (confianza_camara BETWEEN 0 AND 100),
  sensor_confirmado  BOOLEAN      NOT NULL DEFAULT FALSE,
  estado             VARCHAR(12)  NOT NULL
                     CHECK (estado IN ('valido','rechazado','cancelado','duplicado','en_revision')),
  puntos             INTEGER      NOT NULL DEFAULT 0,
  motivo_rechazo     TEXT,
  imagen_url         VARCHAR(500),                                      -- evidencia (MinIO/S3), nunca binario en BD
  revisado_por       BIGINT       REFERENCES usuarios(id),
  created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
  UNIQUE (contenedor_id, uid_evento),
  -- REGLA CENTRAL: solo suma puntos si cámara (material) + sensor lo confirman
  CHECK (
    (estado = 'valido' AND sensor_confirmado AND material_id IS NOT NULL AND puntos > 0)
    OR
    (estado <> 'valido' AND puntos = 0)
  )
);

-- ----------------------------------------------------------------------------
-- 8. ajustes_puntos  (penalizaciones y bonificaciones del administrador)
--    estudiante_id NULL = ajuste colectivo al salón
-- ----------------------------------------------------------------------------
CREATE TABLE ajustes_puntos (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodo_id      BIGINT      NOT NULL REFERENCES periodos_competencia(id),
  salon_id        BIGINT      NOT NULL REFERENCES salones(id),
  estudiante_id   BIGINT      REFERENCES usuarios(id),
  tipo            VARCHAR(12) NOT NULL CHECK (tipo IN ('penalizacion','bonificacion')),
  puntos          INTEGER     NOT NULL CHECK (puntos <> 0),
  motivo          TEXT        NOT NULL CHECK (char_length(btrim(motivo)) >= 5),
  registrado_por  BIGINT      NOT NULL REFERENCES usuarios(id),
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    (tipo = 'penalizacion' AND puntos < 0) OR
    (tipo = 'bonificacion' AND puntos > 0)
  )
);

-- ----------------------------------------------------------------------------
-- 9. log_auditoria
-- ----------------------------------------------------------------------------
CREATE TABLE log_auditoria (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id        BIGINT       REFERENCES usuarios(id) ON DELETE SET NULL,
  accion            VARCHAR(100) NOT NULL,        -- 'AJUSTE_PUNTOS', 'CIERRE_PERIODO', 'LOGIN'...
  entidad           VARCHAR(50)  NOT NULL,
  entidad_id        VARCHAR(100),
  datos_anteriores  JSONB,
  datos_nuevos      JSONB,
  ip                INET,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------------------
-- Triggers updated_at
-- ----------------------------------------------------------------------------
CREATE TRIGGER trg_upd_instituciones BEFORE UPDATE ON instituciones          FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_upd_periodos      BEFORE UPDATE ON periodos_competencia   FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_upd_materiales    BEFORE UPDATE ON materiales_reciclables FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_upd_salones       BEFORE UPDATE ON salones                FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_upd_usuarios      BEFORE UPDATE ON usuarios               FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER trg_upd_contenedores  BEFORE UPDATE ON contenedores           FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ----------------------------------------------------------------------------
-- Índices
-- ----------------------------------------------------------------------------
CREATE INDEX idx_usuarios_salon          ON usuarios (salon_id) WHERE salon_id IS NOT NULL;
CREATE INDEX idx_usuarios_rol            ON usuarios (rol);
CREATE INDEX idx_salones_categoria       ON salones (categoria, grado);
CREATE INDEX idx_contenedores_salon      ON contenedores (salon_id);
CREATE INDEX idx_eventos_salon_periodo   ON eventos_reciclaje (salon_id, periodo_id) WHERE estado = 'valido';
CREATE INDEX idx_eventos_estudiante      ON eventos_reciclaje (estudiante_id, periodo_id) WHERE estudiante_id IS NOT NULL;
CREATE INDEX idx_eventos_contenedor_ts   ON eventos_reciclaje (contenedor_id, ocurrido_en DESC);
CREATE INDEX idx_eventos_estado          ON eventos_reciclaje (estado) WHERE estado IN ('en_revision','rechazado');
CREATE INDEX idx_ajustes_salon_periodo   ON ajustes_puntos (salon_id, periodo_id);
CREATE INDEX idx_ajustes_estudiante      ON ajustes_puntos (estudiante_id, periodo_id) WHERE estudiante_id IS NOT NULL;
CREATE INDEX idx_auditoria_fecha         ON log_auditoria (created_at DESC);
CREATE INDEX idx_auditoria_usuario       ON log_auditoria (usuario_id, created_at DESC);

-- ----------------------------------------------------------------------------
-- VISTAS
-- ----------------------------------------------------------------------------

-- Libro unificado de movimientos de puntos (solo eventos válidos + ajustes)
CREATE VIEW v_movimientos_puntos AS
SELECT 'reciclaje'::text                     AS tipo,
       'E' || e.id                           AS ref,
       e.periodo_id, e.salon_id, e.estudiante_id,
       e.puntos,
       e.ocurrido_en                         AS fecha,
       ('Reciclaje de ' || m.nombre)::text   AS descripcion,
       NULL::bigint                          AS registrado_por
FROM eventos_reciclaje e
JOIN materiales_reciclables m ON m.id = e.material_id
WHERE e.estado = 'valido'
UNION ALL
SELECT a.tipo::text,
       'A' || a.id,
       a.periodo_id, a.salon_id, a.estudiante_id,
       a.puntos,
       a.created_at,
       a.motivo,
       a.registrado_por
FROM ajustes_puntos a;

-- Ranking de salones por categoría y periodo (RANK: los empates comparten posición)
CREATE VIEW v_ranking_salones AS
SELECT s.id            AS salon_id,
       s.nombre        AS salon,
       s.grado,
       s.categoria,
       p.id            AS periodo_id,
       COALESCE(SUM(v.puntos), 0)::int                          AS total_puntos,
       (COUNT(*) FILTER (WHERE v.tipo = 'reciclaje'))::int      AS depositos,
       (RANK() OVER (PARTITION BY s.categoria, p.id
                     ORDER BY COALESCE(SUM(v.puntos), 0) DESC))::int AS posicion
FROM salones s
JOIN periodos_competencia p ON p.institucion_id = s.institucion_id
LEFT JOIN v_movimientos_puntos v ON v.salon_id = s.id AND v.periodo_id = p.id
WHERE s.activo
GROUP BY s.id, p.id;

-- Puntos y posición de cada estudiante dentro de su salón
CREATE VIEW v_puntos_estudiante AS
SELECT u.id            AS estudiante_id,
       u.nombre,
       u.salon_id,
       p.id            AS periodo_id,
       COALESCE(SUM(v.puntos), 0)::int                          AS total_puntos,
       (COUNT(*) FILTER (WHERE v.tipo = 'reciclaje'))::int      AS reciclajes,
       (COUNT(*) FILTER (WHERE v.tipo = 'penalizacion'))::int   AS penalizaciones,
       (RANK() OVER (PARTITION BY u.salon_id, p.id
                     ORDER BY COALESCE(SUM(v.puntos), 0) DESC))::int AS posicion_salon
FROM usuarios u
JOIN periodos_competencia p ON p.institucion_id = u.institucion_id
LEFT JOIN v_movimientos_puntos v ON v.estudiante_id = u.id AND v.periodo_id = p.id
WHERE u.rol = 'estudiante' AND u.activo
GROUP BY u.id, p.id;

COMMIT;
